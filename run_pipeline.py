"""Run the complete analysis pipeline (Parts 1 to 4) end to end.

Usage:
    python run_pipeline.py

Steps:
    1. Build cell_counts.db from cell-count.csv (load_data.py).
    2. Part 2: relative frequency summary table.
    3. Part 3: responder vs non-responder statistics and boxplots.
    4. Part 4: baseline subset counts and the B cell average.

All results are written to the outputs/ directory.
"""

import sys

import pandas as pd

import load_data
from teiko import analysis, plots
from teiko.db import OUTPUT_DIR


def _rule(title: str) -> None:
    print(f"\n{'=' * 72}\n{title}\n{'=' * 72}")


def main() -> int:
    _rule("Part 1: Loading data into SQLite")
    status = load_data.main()
    if status != 0:
        return status

    OUTPUT_DIR.mkdir(exist_ok=True)
    pd.set_option("display.width", 160)
    pd.set_option("display.max_columns", 20)

    # Part 2 ---------------------------------------------------------------
    _rule("Part 2: Relative frequency of each population per sample")
    summary = analysis.frequency_summary()
    summary.to_csv(OUTPUT_DIR / "part2_frequency_summary.csv", index=False)
    print(summary.head(10).to_string(index=False, float_format="%.2f"))
    print(f"... {len(summary):,} rows written to outputs/part2_frequency_summary.csv")

    # Part 3 ---------------------------------------------------------------
    _rule("Part 3: Responders vs non-responders (melanoma, miraclib, PBMC)")
    cohort = analysis.response_cohort()
    sample_level = analysis.compare_responders(cohort, unit="sample")
    subject_level = analysis.compare_responders(cohort, unit="subject")
    by_time = analysis.compare_by_timepoint(cohort)

    sample_level.to_csv(OUTPUT_DIR / "part3_stats_sample_level.csv", index=False)
    subject_level.to_csv(OUTPUT_DIR / "part3_stats_subject_level.csv", index=False)
    by_time.to_csv(OUTPUT_DIR / "part3_stats_by_timepoint.csv", index=False)
    plots.save_static_boxplot(cohort, sample_level, OUTPUT_DIR / "part3_boxplots.png")
    plots.boxplot_figure(cohort, sample_level).write_html(
        OUTPUT_DIR / "part3_boxplots.html", include_plotlyjs="cdn")

    n_samples = cohort["sample"].nunique()
    n_subjects = cohort["subject"].nunique()
    print(f"Cohort: {n_samples} samples from {n_subjects} subjects")
    columns = ["population", "median_responders", "median_non_responders",
               "rank_biserial", "p_value", "q_value_bh", "significant_fdr"]
    print("\nSample-level Mann-Whitney U (two-sided), BH-corrected:")
    print(sample_level[columns].to_string(index=False, float_format="%.4f"))
    print("\nSubject-level (time points averaged per subject):")
    print(subject_level[columns].to_string(index=False, float_format="%.4f"))
    print("\nConclusions:")
    conclusions = analysis.interpret(sample_level, subject_level)
    for line in conclusions:
        print(f"  - {line}")

    # Part 4 ---------------------------------------------------------------
    _rule("Part 4: Baseline melanoma PBMC samples, miraclib-treated")
    baseline = analysis.baseline_samples()
    per_project = analysis.baseline_samples_per_project()
    by_response = analysis.baseline_subjects_by_response()
    by_sex = analysis.baseline_subjects_by_sex()
    b_cells = analysis.average_b_cells_melanoma_male_responders_baseline()

    baseline.to_csv(OUTPUT_DIR / "part4_baseline_samples.csv", index=False)
    per_project.to_csv(OUTPUT_DIR / "part4_samples_per_project.csv", index=False)
    by_response.to_csv(OUTPUT_DIR / "part4_subjects_by_response.csv", index=False)
    by_sex.to_csv(OUTPUT_DIR / "part4_subjects_by_sex.csv", index=False)

    print(f"Baseline samples: {len(baseline)}")
    print("\nSamples per project:")
    print(per_project.to_string(index=False))
    print("\nSubjects by response:")
    print(by_response.to_string(index=False))
    print("\nSubjects by sex:")
    print(by_sex.to_string(index=False))
    print("\nAverage B cell count, melanoma male responders at time 0 "
          f"(all sample types and treatments, n = {b_cells.n_samples}): "
          f"{b_cells.formatted}")

    # Written report ---------------------------------------------------------
    report = [
        "# Analysis results",
        "",
        "Generated by `make pipeline` (run_pipeline.py).",
        "",
        "## Part 3: responders vs non-responders",
        "",
        f"Cohort: melanoma patients treated with miraclib, PBMC samples only, "
        f"{n_samples} samples from {n_subjects} subjects.",
        "",
        "Sample-level two-sided Mann-Whitney U tests, Benjamini-Hochberg "
        "correction across the five populations:",
        "",
        sample_level[columns].to_markdown(index=False, floatfmt=".4f"),
        "",
        "Subject-level robustness check (each subject's time points averaged):",
        "",
        subject_level[columns].to_markdown(index=False, floatfmt=".4f"),
        "",
        *[f"- {line}" for line in conclusions],
        "",
        "![Boxplots](part3_boxplots.png)",
        "",
        "## Part 4: baseline subset",
        "",
        f"Melanoma PBMC samples at time 0 from miraclib-treated subjects: "
        f"{len(baseline)} samples.",
        "",
        per_project.to_markdown(index=False),
        "",
        by_response.to_markdown(index=False),
        "",
        by_sex.to_markdown(index=False),
        "",
        f"Average B cell count for melanoma male responders at time 0 "
        f"(all sample types and treatments): **{b_cells.formatted}**",
        "",
    ]
    (OUTPUT_DIR / "report.md").write_text("\n".join(report), encoding="utf-8")

    _rule("Pipeline complete. Outputs written to outputs/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
